-- DDL corrigido para PostgreSQL.
CREATE SCHEMA IF NOT EXISTS integracao_dados;
SET search_path TO integracao_dados;

CREATE TABLE fornecedor (
    idfornecedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_fornecedor VARCHAR(25) NOT NULL UNIQUE,
    razao_social VARCHAR(255) NOT NULL
);

CREATE TABLE produtos_filial (
    filial_id INTEGER NOT NULL,
    produto_id VARCHAR(255) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    estoque NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    preco_unitario NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (preco_unitario >= 0),
    preco_compra NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (preco_compra >= 0),
    preco_venda NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (preco_venda >= 0),
    codigo_fornecedor VARCHAR(25),
    idfornecedor BIGINT,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT produtos_filial_fornecedor_fk
        FOREIGN KEY (idfornecedor) REFERENCES fornecedor(idfornecedor)
);

CREATE TABLE pedido_compra (
    pedido_id NUMERIC(18,2) NOT NULL DEFAULT 0,
    data_pedido DATE,
    item NUMERIC(12,2) NOT NULL DEFAULT 0,
    produto_id VARCHAR(25) NOT NULL DEFAULT '0',
    descricao_produto VARCHAR(255),
    ordem_compra NUMERIC(18,2) NOT NULL DEFAULT 0,
    qtde_pedida NUMERIC(14,4) CHECK (qtde_pedida IS NULL OR qtde_pedida >= 0),
    filial_id INTEGER,
    data_entrega DATE,
    qtde_entregue NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (qtde_entregue >= 0),
    qtde_pendente NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (qtde_pendente >= 0),
    preco_compra NUMERIC(14,4) DEFAULT 0 CHECK (preco_compra IS NULL OR preco_compra >= 0),
    fornecedor_id BIGINT,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
    CONSTRAINT pedido_compra_fornecedor_fk
        FOREIGN KEY (fornecedor_id) REFERENCES fornecedor(idfornecedor)
);

CREATE TABLE entradas_mercadoria (
    ordem_compra NUMERIC(18,2) NOT NULL DEFAULT 0,
    data_entrada DATE,
    nro_nfe VARCHAR(255) NOT NULL,
    item NUMERIC(12,2) NOT NULL DEFAULT 0,
    produto_id VARCHAR(25) NOT NULL DEFAULT '0',
    descricao_produto VARCHAR(255),
    qtde_recebida NUMERIC(14,4) CHECK (qtde_recebida IS NULL OR qtde_recebida >= 0),
    filial_id INTEGER,
    custo_unitario NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (custo_unitario >= 0),
    CONSTRAINT entradas_mercadoria_pkey
        PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

CREATE TABLE venda (
    venda_id BIGINT NOT NULL,
    data_emissao DATE NOT NULL,
    horariomov VARCHAR(8) NOT NULL DEFAULT '00:00:00',
    produto_id VARCHAR(25) NOT NULL DEFAULT '',
    qtde_vendida NUMERIC(14,4) CHECK (qtde_vendida IS NULL OR qtde_vendida >= 0),
    valor_unitario NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (valor_unitario >= 0),
    filial_id BIGINT NOT NULL DEFAULT 1,
    item INTEGER NOT NULL DEFAULT 0,
    unidade_medida VARCHAR(3),
    CONSTRAINT pk_consumo PRIMARY KEY
        (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

-- Relaciona o código textual F1/F2... ao identificador numérico do fornecedor.
CREATE OR REPLACE FUNCTION fn_vincular_fornecedor_produto()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.codigo_fornecedor IS NULL OR btrim(NEW.codigo_fornecedor) = '' THEN
        NEW.idfornecedor := NULL;
        RETURN NEW;
    END IF;

    SELECT idfornecedor INTO NEW.idfornecedor
      FROM fornecedor
     WHERE codigo_fornecedor = btrim(NEW.codigo_fornecedor);

    IF NEW.idfornecedor IS NULL THEN
        RAISE EXCEPTION 'Fornecedor % não cadastrado', NEW.codigo_fornecedor;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_vincular_fornecedor_produto
BEFORE INSERT OR UPDATE OF codigo_fornecedor ON produtos_filial
FOR EACH ROW EXECUTE FUNCTION fn_vincular_fornecedor_produto();

CREATE INDEX idx_venda_data_produto ON venda(data_emissao, produto_id);
CREATE INDEX idx_pedido_ordem_produto ON pedido_compra(ordem_compra, produto_id, item);
CREATE INDEX idx_entrada_ordem_produto ON entradas_mercadoria(ordem_compra, produto_id, item);
